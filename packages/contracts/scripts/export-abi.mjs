// Writes ABIs straight from Hardhat compile output so apps never hand-copy them.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const names = ["OmnitideUSD", "OmnitideOracle", "OmnitideClearinghouse", "OmnitideHarbor", "OmnitideHarborShare", "OmnitideTideReader", "OmnitideDeepPool", "OmnitideLighthouse", "OmnitideBadge", "OmnitideToken", "OmnitideCouncil", "OmnitideCopyVault", "OmnitideCopyVaultFactory", "OmnitidePort"];
mkdirSync("abi", { recursive: true });
let out = "// Generated by scripts/export-abi.mjs from Hardhat artifacts. Do not edit.\n";
for (const n of names) {
  const { abi } = JSON.parse(readFileSync(`artifacts/contracts/${n}.sol/${n}.json`, "utf8"));
  out += `export const ${n[0].toLowerCase()}${n.slice(1)}Abi = ${JSON.stringify(abi)} as const;\n`;
}
writeFileSync("abi/index.ts", out);
console.log(`abi/index.ts ← ${names.join(", ")}`);
